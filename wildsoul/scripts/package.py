"""Rebuild the source and web-demo ZIPs from this checkout (Python 3 stdlib only).

Run after `npm run build`; the Android project's copied web files are deliberately
excluded from the source snapshot and regenerated by `npm run android:sync`.
"""

from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

ROOT = Path(__file__).resolve().parents[1]
SOURCE_PARTS = (
    ".gitattributes",
    "README.md",
    "ROADMAP.md",
    "capacitor.config.ts",
    "index.html",
    "package.json",
    "package-lock.json",
    "tsconfig.json",
    "vite.config.ts",
    "android",
    "public",
    "scripts",
    "src",
    "store",
    "tests",
)
EXCLUDED_DIRS = {
    ".git", ".gradle", ".idea", ".vite", "__pycache__",
    "build", "coverage", "dist", "node_modules", "out", "target",
}
EXCLUDED_FILES = {"local.properties", "config.xml"}
EXCLUDED_SUFFIXES = {".apk", ".aab", ".jks", ".keystore", ".log", ".zip"}


def source_files():
    for part in SOURCE_PARTS:
        entry = ROOT / part
        if not entry.exists():
            raise FileNotFoundError(entry)
        candidates = entry.rglob("*") if entry.is_dir() else (entry,)
        for file in candidates:
            if not file.is_file():
                continue
            relative = file.relative_to(ROOT)
            if any(component in EXCLUDED_DIRS for component in relative.parts):
                continue
            if relative.parts[:5] == ("android", "app", "src", "main", "assets"):
                continue  # generated by Capacitor from dist/
            if file.name in EXCLUDED_FILES or file.suffix in EXCLUDED_SUFFIXES:
                continue
            if file.name.startswith(".env") or file.name.startswith("google-services"):
                continue  # never package developer configuration or credentials
            yield file


def package(path, files, prefix=""):
    files = sorted(files)
    if not files:
        raise RuntimeError(f"No files to package for {path.name}")
    with ZipFile(path, "w", compression=ZIP_DEFLATED, compresslevel=9) as archive:
        for file in files:
            relative = file.relative_to(ROOT / "dist") if not prefix else file.relative_to(ROOT)
            archive.write(file, prefix + relative.as_posix())
    with ZipFile(path) as archive:
        bad = archive.testzip()
        if bad:
            raise RuntimeError(f"Archive integrity failure: {bad}")
        if len(archive.namelist()) != len(files):
            raise RuntimeError(f"Unexpected file count in {path.name}")
    print(f"{path.name}: {len(files)} verified files, {path.stat().st_size:,} bytes")


if __name__ == "__main__":
    dist = ROOT / "dist"
    if not (dist / "index.html").is_file():
        raise RuntimeError("Missing dist/index.html; run `npm run build` first")
    package(ROOT / "vesperglen-web-demo.zip", (p for p in dist.rglob("*") if p.is_file()))
    package(ROOT / "vesperglen-source.zip", source_files(), "vesperglen/")
